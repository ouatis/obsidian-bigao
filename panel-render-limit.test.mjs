// Installed-bundle regression for the Collate (bigao) plugin.
//
// Since 0.2.0 the installed main.js is an unminified build of src/main.ts,
// so the load-bearing invariant is byte-equality with a fresh source build:
// every source-side test (unit tests, source-bundle tests, parity tests)
// then applies to the installed file as well. The whole-bundle stub test
// below exercises the installed file directly, and the remaining tests
// restate the behavioral guarantees this file previously verified against
// the historical frozen bundle: editor-buffer precedence, comparison
// limits, render revisioning and cursor following.

