test("bounds ordinary full-diff inputs by line and character count", async () => {
  const context = fullDiffContext(async (file) =>
    file === context.state.file1 ? "正文" : "正文");
  const updateState = api.DifferencesView.prototype.updateState;

  assert.equal(await updateState.call(context), true);
  assert.equal(context.comparisonError, null);
  assert.equal(context.file1Content, "正文");

  context.app.vault.cachedRead = async (file) =>
    file === context.state.file1
      ? Array(api.MAX_COMPARISON_LINES + 1).fill("行").join("\n")
      : "短稿";
  assert.equal(await updateState.call(context), true);
  assert.match(context.comparisonError, new RegExp(`${api.MAX_COMPARISON_LINES.toLocaleString()} 行`));

  context.app.vault.cachedRead = async (file) =>
    file === context.state.file1
      ? "字".repeat(api.MAX_COMPARISON_CHARACTERS + 1)
      : "短稿";
  assert.equal(await updateState.call(context), true);
  assert.match(context.comparisonError, new RegExp(`${api.MAX_COMPARISON_CHARACTERS.toLocaleString()} 个字符`));
});

