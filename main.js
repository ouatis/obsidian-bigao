var BigaoPanelView = class extends import_obsidian5.ItemView {
  constructor(leaf, plugin) {
    super(leaf);
    this._plugin = plugin;
    this.compareFile = null;
    this.targetFile = null;
    this.sourceLeaf = null;
    this._timer = null;
    this._lastLine = -1;
    this._follow = true;          // 是否跟随光标
    this._followTimer = null;
    this._followPoll = null;
    this._renderRevision = 0;
  }

  _vault() { return this._plugin && this._plugin.app ? this._plugin.app.vault : null; }

  getViewType() { return BIGAO_PANEL_VIEW; }
  getDisplayText() { return "比稿：对照差异"; }
  getIcon() { return "diff"; }

  setPair(targetFile, compareFile, sourceLeaf) {
    this.targetFile = targetFile;
    this.compareFile = compareFile;
    this.sourceLeaf = sourceLeaf || null;
    this._follow = true;
    this._lastLine = -1;
    this._startFollowPolling();
    this.scheduleRender();
  }

  clearPair() {
    this._renderRevision += 1;
    this.targetFile = null;
    this.compareFile = null;
    this.sourceLeaf = null;
    if (this._timer) { clearTimeout(this._timer); this._timer = null; }
    if (this._followTimer) { clearTimeout(this._followTimer); this._followTimer = null; }
    this._stopFollowPolling();
    try { this.contentEl.empty(); } catch (e) {}
  }

  scheduleRender() {
    var revision = ++this._renderRevision;
    if (this._timer) clearTimeout(this._timer);
    var self = this;
    this._timer = setTimeout(function () { self._timer = null; self.renderNow(revision); }, BigaoPanel.DEBOUNCE_MS);
  }

  // 面板上的控件
  _buildChrome(container, count) {
    var head = container.createDiv({ cls: "bigao-panel__head" });
    head.createDiv({ cls: "bigao-panel__count", text: count + " 处差异" });
    var self = this;
    var btn = head.createDiv({ cls: "bigao-panel__follow" });
    btn.setAttribute("data-active", this._follow ? "1" : "0");
    btn.setAttribute("title", "点击切换是否跟随光标");
    btn.createSpan({ text: this._follow ? "跟随中" : "不跟随" });
    try {
      btn.addEventListener("click", function () {
        self._follow = !self._follow;
        btn.setAttribute("data-active", self._follow ? "1" : "0");
        btn.empty();
        btn.createSpan({ text: self._follow ? "跟随中" : "不跟随" });
        if (self._follow) {
          self._startFollowPolling();
          self.followCursor(true);
        } else {
          self._stopFollowPolling();
        }
        new Notice(self._follow ? "比稿：面板将跟随光标" : "比稿：面板已停止跟随");
      });
    } catch (e) { /* 无 DOM 环境时忽略 */ }
    return head;
  }

  async renderNow(renderRevision = this._renderRevision) {
    if (renderRevision !== this._renderRevision) return;
    var targetFile = this.targetFile;
    var compareFile = this.compareFile;
    try {
      var vault = this._vault();
      if (!vault) return;
      if (!compareFile || !targetFile) {
        this.contentEl.empty();
        this.contentEl.createDiv({ cls: "bigao-panel__empty", text: "用「比稿：开启左右分屏对照」选择一篇对照稿。" });
        return;
      }
      var mainText = _bigaoReadOpenEditorText(this._plugin, targetFile);
      if (mainText === null) mainText = await vault.cachedRead(targetFile);
      if (renderRevision !== this._renderRevision) return;
      var otherText = _bigaoReadOpenEditorText(this._plugin, compareFile);
      if (otherText === null) otherText = await vault.cachedRead(compareFile);
      if (renderRevision !== this._renderRevision) return;
      var lines = mainText.split("\n");
      var otherLineCount = otherText.split("\n").length;
      if (lines.length > MAX_LINES || otherLineCount > MAX_LINES) {
        this.contentEl.empty();
        this.contentEl.createDiv({
          cls: "bigao-panel__empty",
          text: "任一篇笔记超过 " + MAX_LINES + " 行，分屏对照暂不计算。",
        });
        return;
      }
      var diffs = BigaoPanel.compute(mainText, otherText);
      var container = this.contentEl;
      container.empty();
      this._buildChrome(container, diffs.length);
      this._body = BigaoPanelRender.renderFull(container, lines, diffs);
      this.followCursor(false);
    } catch (e) {
      if (renderRevision !== this._renderRevision) return;
      console.error("比稿：面板更新失败", e);
      try {
        this.contentEl.empty();
        this.contentEl.createDiv({ cls: "bigao-panel__empty", text: "更新失败：" + e.message });
      } catch (e2) { /* 面板失败不影响主功能 */ }
    }
  }

  // 跟随主笔记光标
  followCursor(force) {
    if (!this._follow || !this._body) return;
    try {
      var workspace = this._plugin && this._plugin.app ? this._plugin.app.workspace : null;
      if (!workspace || !this.targetFile) return;
      var view = this.sourceLeaf && this.sourceLeaf.view;
      if (!view || !view.file || view.file.path !== this.targetFile.path || !view.editor) {
        var leaves = typeof workspace.getLeavesOfType === "function"
          ? workspace.getLeavesOfType("markdown")
          : [];
        view = null;
        for (var i = 0; i < leaves.length; i++) {
          var candidate = leaves[i] && leaves[i].view;
          if (candidate && candidate.file && candidate.file.path === this.targetFile.path && candidate.editor) {
            view = candidate;
            break;
          }
        }
      }
      if (!view && typeof workspace.getActiveViewOfType === "function") {
        view = workspace.getActiveViewOfType(MarkdownView);
      }
      if (!view || !view.editor || !view.file || view.file.path !== this.targetFile.path) return;
      var line = view.editor.getCursor("from").line;
      if (!force && line === this._lastLine) return;
      this._lastLine = line;
      BigaoPanelRender.scrollToLine(this._body, line, true);
    } catch (e) { /* 定位失败不影响阅读 */ }
  }

  onCursorMoved() {
    if (this._followTimer) clearTimeout(this._followTimer);
    var self = this;
    this._followTimer = setTimeout(function () {
      self._followTimer = null;
      self.followCursor(false);
    }, 120);
  }

  _startFollowPolling() {
    if (!this._follow || !this.targetFile || this._followPoll) return;
    var self = this;
    this._followPoll = setInterval(function () { self.followCursor(false); }, 250);
  }

  _stopFollowPolling() {
    if (!this._followPoll) return;
    clearInterval(this._followPoll);
    this._followPoll = null;
  }

  async onOpen() {
    try {
      this.contentEl.empty();
      this.contentEl.createDiv({ cls: "bigao-panel__empty", text: "用「比稿：开启左右分屏对照」选择一篇对照稿。" });
      var self = this;
      var app = this._plugin ? this._plugin.app : null;
      if (app && app.workspace && typeof app.workspace.on === "function") {
        this.registerEvent(app.workspace.on("editor-change", function (editor, info) {
          var file = info && info.file;
          if (!file) return;
          if (self.targetFile && file.path === self.targetFile.path) {
            self.scheduleRender();
            self.onCursorMoved();
          } else if (self.compareFile && file.path === self.compareFile.path) {
            self.scheduleRender();
          }
        }));
      }
      var ref = this._vault();
      if (ref && typeof ref.on === "function") {
        this.registerEvent(ref.on("modify", function (file) {
          if (!file) return;
          if ((self.targetFile && file.path === self.targetFile.path) ||
              (self.compareFile && file.path === self.compareFile.path)) {
            self.scheduleRender();
          }
        }));
      }
    } catch (e) {
      console.error("比稿：面板打开失败", e);
    }
  }

  async onClose() {
    this._renderRevision += 1;
    if (this._timer) clearTimeout(this._timer);
    if (this._followTimer) clearTimeout(this._followTimer);
    this._stopFollowPolling();
  }
};

