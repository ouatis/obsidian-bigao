var FileDiffPlugin = class extends import_obsidian5.Plugin {
  constructor() {
    super(...arguments);
    this.fileDiffMergeWarningKey = "bigao-merge-warning";
  }
  onload() {
    __bigaoApplyPalette();
    try {
      BigaoInlineDiffRuntime = _bigaoLoadInlineDiffRuntime(this);
      BigaoInlineDiffRuntime.registerInlineDiffRuntime(this);
    } catch (error) {
      BigaoInlineDiffRuntime = null;
      console.error("比稿：行内差异模块加载失败", error);
    }
    // 启动自检：一旦加载成功就在控制台留痕，便于区分"没加载"与"功能故障"
    try {
      console.log("[比稿] 插件已加载 · 命令已注册 · 原生分屏对照可用");
    } catch (e) {}
    this.registerView(
      VIEW_TYPE_DIFFERENCES,
      (leaf) => new DifferencesView(leaf)
    );

    var _self = this;
    var _plugin = this;
    this.registerView(BIGAO_PANEL_VIEW, (leaf) => new BigaoPanelView(leaf, _plugin));
    this.addCommand({
      id: "bigao-panel-on",
      name: "比稿：开启左右分屏对照",
      callback: () => _bigaoStartSplitComparison(_plugin, "vertical")
    });
    this.addCommand({
      id: "bigao-panel-on-horizontal",
      name: "比稿：开启上下分屏对照",
      callback: () => _bigaoStartSplitComparison(_plugin, "horizontal")
    });
    this.addCommand({
      id: "bigao-panel-off",
      name: "比稿：关闭分屏对照",
      callback: () => {
        const closedCount = _bigaoCloseSplitComparison(this.app);
        new Notice(closedCount > 0 ? "比稿：分屏对照已关闭" : "比稿：没有由比稿创建的分屏对照窗格");
      }
    });
    this.addCommand({
      id: "bigao-compare",
      name: "比稿：对比两篇",
      editorCallback: async () => {
        const activeFile = this.app.workspace.getActiveFile();
        if (activeFile == null) {
          return;
        }
        const compareFile = await this.getFileToCompare(activeFile);
        if (compareFile == null) {
          return;
        }
        this.openDifferencesView({
          file1: activeFile,
          file2: compareFile,
          showMergeOption: false
        });
      }
    });
    this.addCommand({
      id: "bigao-compare-and-merge",
      name: "比稿：对比并合并",
      editorCallback: async () => {
        if (!localStorage.getItem(this.fileDiffMergeWarningKey)) {
          await this.showRiskyActionModal();
          if (!localStorage.getItem(this.fileDiffMergeWarningKey)) {
            return;
          }
        }
        const activeFile = this.app.workspace.getActiveFile();
        if (activeFile == null) {
          return;
        }
        const compareFile = await this.getFileToCompare(activeFile);
        if (compareFile == null) {
          return;
        }
        this.openDifferencesView({
          file1: activeFile,
          file2: compareFile,
          showMergeOption: true
        });
      }
    });
    this.addCommand({
      id: "bigao-find-sync-conflicts",
      name: "比稿：查找同步冲突并合并",
      callback: async () => {
        if (!localStorage.getItem(this.fileDiffMergeWarningKey)) {
          await this.showRiskyActionModal();
          if (!localStorage.getItem(this.fileDiffMergeWarningKey)) {
            return;
          }
        }
        const syncConflicts = this.findSyncConflicts();
        for await (const syncConflict of syncConflicts) {
          const continuePromise = new Promise((resolve) => {
            this.openDifferencesView({
              file1: syncConflict.originalFile,
              file2: syncConflict.syncConflictFile,
              showMergeOption: true,
              continueCallback: async (shouldContinue2) => resolve(shouldContinue2)
            });
          });
          const shouldContinue = await continuePromise;
          if (!shouldContinue) {
            break;
          }
        }
      }
    });
  }
  async onunload() {
    this.app.workspace.detachLeavesOfType(VIEW_TYPE_DIFFERENCES);
    this.app.workspace.detachLeavesOfType(BIGAO_PANEL_VIEW);
  }
  getFileToCompare(activeFile) {
    return _bigaoPickCompareFile(this, activeFile);
  }
  showRiskyActionModal() {
    return new Promise((resolve, reject) => {
      new RiskyActionModal({
        app: this.app,
        onAccept: async (e) => {
          if (e) {
            reject(e);
          } else {
            localStorage.setItem(
              this.fileDiffMergeWarningKey,
              "true"
            );
            await sleep(50);
            resolve();
          }
        }
      }).open();
    });
  }
  async openDifferencesView(state) {
    this.app.workspace.detachLeavesOfType(VIEW_TYPE_DIFFERENCES);
    const leaf = this.app.workspace.getLeaf(true);
    leaf.setViewState({
      type: VIEW_TYPE_DIFFERENCES,
      active: true,
      state
    });
    this.app.workspace.revealLeaf(leaf);
  }
  findSyncConflicts() {
    const syncConflicts = [];
    const files = this.app.vault.getMarkdownFiles();
    for (const file of files) {
      if (file.name.includes("sync-conflict")) {
        const originalFileName = file.name.replace(
          /\.sync-conflict-\d{8}-\d{6}-[A-Z0-9]+/,
          ""
        );
        const originalFile = files.find(
          (f) => {
            var _a, _b, _c, _d;
            return f.name === originalFileName && ((_b = (_a = file.parent) == null ? void 0 : _a.path) != null ? _b : "") === ((_d = (_c = f.parent) == null ? void 0 : _c.path) != null ? _d : "");
          }
        );
        if (originalFile) {
          syncConflicts.push({
            originalFile,
            syncConflictFile: file
          });
        }
      }
    }
    return syncConflicts;
  }
};
