var import_obsidian = require("obsidian");
async function readOpenEditorText(app, file) {
  try {
    const activeView = app.workspace.getActiveViewOfType(import_obsidian.MarkdownView);
    if (activeView?.file?.path === file.path && typeof activeView.editor?.getValue === "function") {
      return activeView.editor.getValue();
    }
    for (const leaf of app.workspace.getLeavesOfType("markdown")) {
      const view = leaf.view;
      if (view instanceof import_obsidian.MarkdownView && view.file?.path === file.path && typeof view.editor?.getValue === "function") {
        return view.editor.getValue();
      }
    }
  } catch {
  }
  return app.vault.cachedRead(file);
}

