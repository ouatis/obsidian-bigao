// 选择一篇对照稿。取消时 resolve(null)，绝不 reject。
async function _bigaoPickCompareFile(plugin, activeFile) {
  var all = plugin.app.vault.getMarkdownFiles();
  var files = all.filter(function (f) { return f.path !== activeFile.path; });
  if (!files.length) {
    new Notice("库里没有其他笔记可作为对照");
    return null;
  }
  files.sort(function (a, b) { return (a.stat && a.stat.mtime) > (b.stat && b.stat.mtime) ? -1 : 1; });
  return new Promise(function (resolve) {
    var settled = false;
    function done(v) { if (!settled) { settled = true; resolve(v); } }
    var timer = setTimeout(function () { done(null); }, 60000);   // 兜底，避免永久挂起
    var modal = new BigaoPickModal(plugin.app, files);
    modal.onResolve = function (v) { clearTimeout(timer); done(v); };
    console.log("[比稿] 选择器：准备打开，候选", files.length, "篇");
    try {
      modal.setPlaceholder("选择一篇作为对照稿…（可输入名称或路径筛选）");
      console.log("[比稿] 选择器：调用 open()");
      modal.open();
      console.log("[比稿] 选择器：open() 已返回，modalEl 在 DOM 中 =",
        !!(modal.modalEl && modal.modalEl.isConnected));
    } catch (e) {
      console.error("[比稿] 选择器：open() 抛错", e);
      clearTimeout(timer);
      done(null);
    }
  });
}

// Put the existing comparison view into an Obsidian-native split beside the
// source editor instead of opening it as an unrelated workspace tab.
async function _bigaoOpenSplitComparison(plugin, targetFile, compareFile, sourceLeaf, direction) {
  var workspace = plugin && plugin.app && plugin.app.workspace;
  if (!workspace || !sourceLeaf || typeof workspace.createLeafBySplit !== "function") {
    new Notice("比稿：无法取得当前编辑窗格，未打开对照");
    return false;
  }
  var splitDirection = direction === "horizontal" ? "horizontal" : "vertical";
  var previousLeaves = typeof workspace.getLeavesOfType === "function"
    ? workspace.getLeavesOfType(BIGAO_PANEL_VIEW).slice()
    : [];
  var markdownLeaves = typeof workspace.getLeavesOfType === "function"
    ? workspace.getLeavesOfType("markdown")
    : [];
  var existing = null;
  _bigaoSplitComparisons.forEach(function (comparison, leaf) {
    if (!existing && comparison.sourceLeaf === sourceLeaf && comparison.direction === splitDirection && (comparison.sourcePath || (sourceLeaf.view instanceof MarkdownView && sourceLeaf.view.file && sourceLeaf.view.file.path)) === targetFile.path && markdownLeaves.includes(leaf) && leaf.view instanceof MarkdownView && leaf.view.file && leaf.view.file.path === comparison.comparePath) {
      existing = [leaf, comparison];
    }
  });
  if (existing) {
    try {
      await existing[0].openFile(compareFile, { active: true });
      if (!(existing[0].view instanceof MarkdownView) || !existing[0].view.file || existing[0].view.file.path !== compareFile.path) {
        throw new Error("「" + (compareFile.name || compareFile.path) + "」没有载入分屏窗格");
      }
      existing[1].comparePath = compareFile.path;
      existing[1].sourcePath = targetFile.path;
      workspace.revealLeaf(existing[0]);
      if (BigaoInlineDiffRuntime) BigaoInlineDiffRuntime.scheduleInlineDiffRefresh(plugin.app);
      new Notice("比稿：已在" + (splitDirection === "vertical" ? "左右" : "上下") + "分屏中打开「" + compareFile.name + "」");
      return true;
    } catch (error) {
      console.error("比稿：更新分屏对照失败", error);
      new Notice("比稿：打开分屏对照失败 —— " + error.message);
      return false;
    }
  }
  var leaf = null;
  try {
    leaf = workspace.createLeafBySplit(sourceLeaf, splitDirection);
    if (!leaf) throw new Error("Obsidian 未能创建分屏");
    await leaf.openFile(compareFile, { active: true });
    if (!(leaf.view instanceof MarkdownView) || !leaf.view.file || leaf.view.file.path !== compareFile.path) {
      throw new Error("「" + (compareFile.name || compareFile.path) + "」没有载入分屏窗格");
    }
    workspace.revealLeaf(leaf);
    _bigaoSplitComparisons.set(leaf, {
      comparePath: compareFile.path,
      sourcePath: targetFile.path,
      direction: splitDirection,
      sourceLeaf: sourceLeaf
    });
    for (var i = 0; i < previousLeaves.length; i++) {
      if (previousLeaves[i] !== leaf && typeof previousLeaves[i].detach === "function") {
        previousLeaves[i].detach();
      }
    }
    if (BigaoInlineDiffRuntime) BigaoInlineDiffRuntime.scheduleInlineDiffRefresh(plugin.app);
    new Notice("比稿：已在" + (splitDirection === "vertical" ? "左右" : "上下") + "分屏中打开「" + compareFile.name + "」");
    return true;
  } catch (error) {
    try { if (leaf && typeof leaf.detach === "function") leaf.detach(); } catch (e) { /* best effort */ }
    console.error("比稿：打开分屏对照失败", error);
    new Notice("比稿：打开分屏对照失败 —— " + error.message);
    return false;
  }
}

function _bigaoCloseSplitComparison(app) {
  var workspace = app && app.workspace;
  if (!workspace) return 0;
  var markdownLeaves = new Set(workspace.getLeavesOfType("markdown"));
  var closedCount = 0;
  _bigaoSplitComparisons.forEach(function (comparison, leaf) {
    if (BigaoInlineDiffRuntime) BigaoInlineDiffRuntime.clearInlineDiffForLeaves(comparison.sourceLeaf, leaf);
    if (markdownLeaves.has(leaf) && leaf.view instanceof MarkdownView && leaf.view.file && leaf.view.file.path === comparison.comparePath) {
      leaf.detach();
      closedCount += 1;
    }
  });
  _bigaoSplitComparisons.clear();
  return closedCount;
}

